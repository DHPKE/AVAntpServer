"""Pure functions: validated config -> file contents. No I/O, so they are unit-testable anywhere."""
import ipaddress

HDR = "# Generated by AVAntpServer - do not edit by hand, change it in the WebUI.\n"


def chrony(cfg):
    up = cfg["upstream"]
    out = [HDR]
    for h in up["default"]:
        out.append(f"pool {h} iburst prefer\n" if not _is_ip(h) else f"server {h} iburst prefer\n")
    for h in up["backup"] + up["custom"]:
        out.append(f"server {h} iburst\n")
    out.append(
        "driftfile /var/lib/chrony/chrony.drift\n"
        "makestep 1.0 3\n"
        "rtcsync\n"
        "leapsectz right/UTC\n"
        "bindcmdaddress 127.0.0.1\n"
        "bindcmdaddress ::1\n"
        "ratelimit interval 1 burst 16 leak 2\n"
    )
    serving = [v for v in cfg["vlans"] if v["ntp"]]
    if any(v["mode"] == "dhcp" for v in serving):
        out.append("allow all\n")  # DHCP VLAN subnets are unknown here; nftables restricts by interface
    else:
        for v in serving:
            out.append(f"allow {v['_if'].network}\n")
    if up["local_fallback"]:
        out.append("local stratum 10 orphan\n")
    return "".join(out)


def _is_ip(h):
    try:
        ipaddress.ip_address(h)
        return True
    except ValueError:
        return False


def networkd(cfg):
    """Return {filename: content} for /etc/systemd/network."""
    wan, lan = cfg["wan"], cfg["lan"]
    files = {}
    w = [HDR, f"[Match]\nName={wan['iface']}\n\n[Network]\nLinkLocalAddressing=no\nIPv6AcceptRA=no\n"]
    if wan["mode"] == "dhcp":
        w.append("DHCP=ipv4\n\n[DHCPv4]\nUseNTP=no\nUseHostname=no\nUseDomains=no\n")
    else:
        w.append(f"Address={wan['address']}\nGateway={wan['gateway']}\n")
        for d in wan["dns"]:
            w.append(f"DNS={d}\n")
    files["10-avantp-wan.network"] = "".join(w)
    vl = "".join(f"VLAN={v['iface']}\n" for v in cfg["vlans"])
    files["20-avantp-lan.network"] = (
        f"{HDR}[Match]\nName={lan['iface']}\n\n[Network]\nLinkLocalAddressing=no\nIPv6AcceptRA=no\n"
        f"ConfigureWithoutCarrier=yes\n{vl}")
    for v in cfg["vlans"]:
        files[f"30-avantp-{v['iface']}.netdev"] = (
            f"{HDR}[NetDev]\nName={v['iface']}\nKind=vlan\n\n[VLAN]\nId={v['id']}\n")
        n = [HDR, f"[Match]\nName={v['iface']}\n\n[Network]\nLinkLocalAddressing=no\nIPv6AcceptRA=no\n"
                  "ConfigureWithoutCarrier=yes\n"]
        if v["mode"] == "static":
            n.append(f"Address={v['_if']}\n")  # deliberately no Gateway/DNS: LAN side never routes
        else:
            # a LAN-side DHCP server must not be able to push routes, DNS or NTP onto the box
            n.append("DHCP=ipv4\n\n[DHCPv4]\nUseRoutes=no\nUseGateway=no\nUseDNS=no\nUseNTP=no\n"
                     "UseHostname=no\nUseDomains=no\nSendHostname=no\n")
        files[f"30-avantp-{v['iface']}.network"] = "".join(n)
    return files


def sysctl(cfg):
    return HDR + (
        "net.ipv4.ip_forward=0\n"
        "net.ipv6.conf.all.forwarding=0\n"
        "net.ipv4.conf.all.rp_filter=1\n"
        "net.ipv4.conf.default.rp_filter=1\n"
        "net.ipv4.conf.all.arp_ignore=1\n"
        "net.ipv4.conf.all.arp_announce=2\n"
        "net.ipv4.conf.all.accept_redirects=0\n"
        "net.ipv4.conf.all.send_redirects=0\n"
        "net.ipv4.conf.all.accept_source_route=0\n"
    )


def nftables(cfg):
    wan = cfg["wan"]["iface"]
    port = cfg["webui"]["port"]
    inp, outp = [], []
    for v in cfg["vlans"]:
        i = v["iface"]
        inp.append(f'    # VLAN {v["id"]} {v["name"]}')
        to = f' ip daddr {v["_if"].ip}' if v["mode"] == "static" else ""  # a host on VLAN A cannot use VLAN B's address
        inp.append(f'    iifname "{i}" icmp type echo-request limit rate 5/second accept')
        if v["ntp"]:
            inp.append(f'    iifname "{i}"{to} udp dport 123 accept')
        if v["mgmt"]:
            inp.append(f'    iifname "{i}"{to} tcp dport {{ 22, {port} }} accept')
        if v["mode"] == "dhcp":
            inp.append(f'    iifname "{i}" udp sport 67 udp dport 68 accept')
            outp.append(f'    oifname "{i}" udp sport 68 udp dport 67 accept')
        tc = v["timecode"]
        if tc["artnet"]:
            outp.append(f'    oifname "{i}" udp dport 6454 accept')
        if tc["mtc_rtp"]:
            inp.append(f'    iifname "{i}" udp dport {{ 5004, 5005 }} accept')
            outp.append(f'    oifname "{i}" udp dport {{ 5004, 5005 }} accept')
    wan_ssh_in = (f'    # COMMISSIONING ONLY: SSH + WebUI from the WAN side, switch off once the management VLAN works\n'
                  f'    iifname "{wan}" tcp dport {{ 22, {port} }} accept\n') if cfg["wan"]["commissioning"] else ""
    wan_dhcp_in = f'    iifname "{wan}" udp sport 67 udp dport 68 accept\n' if cfg["wan"]["mode"] == "dhcp" else ""
    wan_dhcp_out = f'    oifname "{wan}" udp sport 68 udp dport 67 accept\n' if cfg["wan"]["mode"] == "dhcp" else ""
    nl = "\n"
    return f"""{HDR}table inet avantp
delete table inet avantp

table inet avantp {{
  # "Update mode": the root helper adds the WAN interface here with a timeout; the kernel removes it again by itself
  set update_window {{
    type ifname
    flags timeout
  }}
  chain input {{
    type filter hook input priority 0; policy drop;
    iifname "lo" accept
    ct state invalid drop
    ct state established,related accept
    # WAN: nothing may initiate a connection to this box
{wan_dhcp_in}{wan_ssh_in}{nl.join(inp)}
  }}
  chain forward {{
    # the two sides are never connected: no rules, policy drop
    type filter hook forward priority 0; policy drop;
  }}
  chain output {{
    type filter hook output priority 0; policy drop;
    oifname "lo" accept
    ct state established,related accept
    # WAN: only what an NTP client needs (NTP, NTS-KE, DNS, DHCP)
    oifname "{wan}" udp dport 123 accept
    oifname "{wan}" tcp dport 4460 accept
    oifname "{wan}" meta l4proto {{ udp, tcp }} th dport 53 accept
    oifname @update_window tcp dport {{ 80, 443 }} accept   # package updates, only while Update mode is on
{wan_dhcp_out}{nl.join(outp)}
  }}
}}
"""


def render_all(cfg):
    """Return {relative path under / : content}."""
    files = {
        "etc/chrony/chrony.conf": chrony(cfg),
        "etc/sysctl.d/90-avantp.conf": sysctl(cfg),
        "etc/avantp/nftables.nft": nftables(cfg),
    }
    for name, body in networkd(cfg).items():
        files[f"etc/systemd/network/{name}"] = body
    return files
